// Generates the two signing key pairs (ECDSA P-256) and the public half the extension ships with.
//   node tools/gen-keys.mjs [--force] [--production] [--root <dir>]        (npm run keys)
//
// public-keys.js ends with an explicit sentinel, `export const KEY_STATUS = 'dev' | 'production'`, and tools/package.mjs tests
// THAT (not the header prose) before it builds a release. Default and --force write 'dev'. --production makes fresh pairs
// (it never relabels existing ones: a label flip would defeat the guard) and writes 'production'. An idempotent re-run keeps the
// status the file already has while the keys are unchanged.
//
// Production private keys do not belong in .keys/ on a developer machine: generate them in a KMS/HSM (or on an offline machine),
// paste ONLY the public JWKs into src/shared/public-keys.js and set KEY_STATUS = 'production' there by hand, and sign the selector
// map and licences from that environment. --production exists for a single-owner setup and still leaves plain private files in
// .keys/ (mode 0600): move them out and back them up.
//
//   .keys/selector-map.private.jwk.json   signs src/data/selector-map.signed.json   (kid selector-map-N)
//   .keys/licence.private.jwk.json        signs licence tokens                      (kid licence-N)
//   src/shared/public-keys.js             the public JWKs, imported by the extension
//
// Idempotent: existing private keys are reused (public-keys.js is rebuilt from them, byte-identical when nothing changed).
// It never replaces an existing private key, and never rewrites a public-keys.js that disagrees with the private keys,
// unless --force is given. --force makes fresh pairs under the next kid number and keeps the old private files as
// `<name>.private.jwk.<timestamp>.bak.json` in .keys/.
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { signPayload, toPublicJwk, verifyEnvelope } from '../src/shared/signing.js';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const KEY_SPECS = [
  { name: 'selector-map', exportName: 'SELECTOR_MAP_PUBLIC_KEY', purpose: 'signs the selector map' },
  { name: 'licence', exportName: 'LICENCE_PUBLIC_KEY', purpose: 'signs licence tokens' },
];

export const privateKeyPath = (root, name) => join(root, '.keys', `${name}.private.jwk.json`);
export const publicKeysPath = (root) => join(root, 'src', 'shared', 'public-keys.js');

export const KEY_STATUSES = ['dev', 'production'];

const HEADERS = {
  dev: `// GENERATED by tools/gen-keys.mjs (npm run keys). Do not edit by hand.
//
// !! DEV KEYS !!  These public keys belong to throw-away development key pairs. Before ANY Chrome Web Store release the
// owner must replace them with production keys (npm run keys -- --production, or paste the public JWKs of keys generated in a
// KMS/HSM and set KEY_STATUS = 'production'), then re-run npm run sign-map and issue licences with the new licence key.
// Anything signed with a dev key can be forged by whoever holds this machine's .keys/ folder.
//
// The private halves live in .keys/ (gitignored, never bundled into the extension). Back that folder up: losing it means
// no new selector map or licence can be signed for these public keys. Never commit it.
//
// tools/package.mjs releases only when KEY_STATUS below is 'production'.
`,
  production: `// GENERATED by tools/gen-keys.mjs (npm run keys -- --production). Do not edit by hand, except to paste KMS/HSM public keys.
//
// PRODUCTION KEYS. The private halves must live in a KMS/HSM or an offline store, not in a working copy: move them out of .keys/
// (gitignored, never bundled) and back them up. Losing them means no new selector map or licence can be signed for these public
// keys; anyone who gets them can mint Pro licences and maps that every installed extension trusts. Never commit them.
//
// tools/package.mjs releases only when KEY_STATUS below is 'production'.
`,
};

export class ToolError extends Error {}

const isPlain = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);

/** Same key material (x and y), whatever the kid or extra members. */
const sameKey = (a, b) => isPlain(a) && isPlain(b) && a.x === b.x && a.y === b.y;

function nextKid(name, previous) {
  const match = typeof previous === 'string' && previous.startsWith(`${name}-`) ? /^(\d+)$/.exec(previous.slice(name.length + 1)) : null;
  return `${name}-${match ? Number(match[1]) + 1 : 1}`;
}

async function generatePair(name, kid) {
  const pair = await globalThis.crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify']);
  const jwk = await globalThis.crypto.subtle.exportKey('jwk', pair.privateKey);
  return { kty: 'EC', crv: 'P-256', x: jwk.x, y: jwk.y, d: jwk.d, kid };
}

/** Sign and verify a probe, so a private key whose `d` does not belong to its x/y is caught before it is trusted. */
async function selfTest(privateJwk) {
  const publicJwk = toPublicJwk(privateJwk);
  const payload = `cinedrape-self-test:${privateJwk.kid}`;
  const sig = await signPayload(payload, privateJwk);
  const result = await verifyEnvelope({ payload, sig, kid: privateJwk.kid }, publicJwk);
  if (!result.ok) throw new Error(`self-test failed: ${result.reason}`);
}

function readPrivateKey(file, name) {
  let jwk;
  try {
    jwk = JSON.parse(readFileSync(file, 'utf8'));
  } catch (err) {
    throw new ToolError(`${file} is not readable JSON (${err.message}). Fix or move it; refusing to overwrite a private key (use --force to replace it).`);
  }
  if (!isPlain(jwk) || jwk.kty !== 'EC' || jwk.crv !== 'P-256' || ['x', 'y', 'd'].some((k) => typeof jwk[k] !== 'string')) {
    throw new ToolError(`${file} is not a P-256 private JWK. Fix or move it; refusing to overwrite a private key (use --force to replace it).`);
  }
  return { ...jwk, kid: typeof jwk.kid === 'string' && jwk.kid ? jwk.kid : `${name}-1` };
}

async function readExistingPublicKeys(file) {
  if (!existsSync(file)) return null;
  try {
    return await import(`${pathToFileURL(file).href}?t=${Date.now()}-${Math.random()}`);
  } catch {
    return null;
  }
}

/**
 * The status sentinel of the shipped public-keys.js: 'dev', 'production', or null when the file is missing, unreadable or has none
 * (a hand-edited or pre-sentinel file). tools/package.mjs releases only on 'production'.
 */
export async function readKeyStatus(root = REPO_ROOT) {
  const shipped = await readExistingPublicKeys(publicKeysPath(root));
  return shipped && KEY_STATUSES.includes(shipped.KEY_STATUS) ? shipped.KEY_STATUS : null;
}

/**
 * For the signing tools: the private key `name` plus the public key the extension ships for it, checked to be a matching
 * pair (otherwise whatever gets signed would be rejected by every installed extension).
 * @returns {Promise<{privateJwk: object, publicJwk: object}>}
 */
export async function loadKeyPair(root, name) {
  const spec = KEY_SPECS.find((s) => s.name === name);
  if (!spec) throw new Error(`unknown key ${name}`);
  const file = privateKeyPath(root, name);
  if (!existsSync(file)) throw new ToolError(`private key ${file} not found. Run "npm run keys" first.`);
  const privateJwk = readPrivateKey(file, name);
  const shipped = await readExistingPublicKeys(publicKeysPath(root));
  const publicJwk = shipped && shipped[spec.exportName];
  if (!publicJwk) throw new ToolError(`${publicKeysPath(root)} is missing or has no ${spec.exportName}. Run "npm run keys".`);
  if (!sameKey(publicJwk, privateJwk) || publicJwk.kid !== privateJwk.kid) {
    throw new ToolError(`${file} (kid ${privateJwk.kid}) does not match ${spec.exportName} in public-keys.js (kid ${publicJwk.kid}); the extension would reject what it signs. Restore the matching key, or run "npm run keys -- --force" and re-sign.`);
  }
  await selfTest(privateJwk);
  return { privateJwk, publicJwk };
}

const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

export function renderPublicKeysModule(keys, status = 'dev') {
  if (!KEY_STATUSES.includes(status)) throw new ToolError(`unknown key status ${JSON.stringify(status)} (expected ${KEY_STATUSES.join(' or ')})`);
  const blocks = KEY_SPECS.map(({ name, exportName }) => {
    const k = keys[name];
    return `export const ${exportName} = Object.freeze({\n  kty: ${quote(k.kty)},\n  crv: ${quote(k.crv)},\n  x: ${quote(k.x)},\n  y: ${quote(k.y)},\n  kid: ${quote(k.kid)},\n});\n`;
  });
  const sentinel = `// 'dev' | 'production'. The release script tests this value, not the wording of the header.\nexport const KEY_STATUS = ${quote(status)};\n`;
  return `${HEADERS[status]}\n${blocks.join('\n')}\n${sentinel}`;
}

function writeAtomic(file, text, options) {
  mkdirSync(dirname(file), { recursive: true });
  const tmp = `${file}.tmp-${process.pid}`;
  writeFileSync(tmp, text, options);
  renameSync(tmp, file);
}

/**
 * @param {{root?: string, force?: boolean, production?: boolean, log?: (line: string) => void}} [options]
 *   production: fresh pairs (like force) and KEY_STATUS 'production'
 * @returns {Promise<{generated: string[], reused: string[], backups: string[], wrotePublicKeys: boolean, publicKeysFile: string}>}
 */
export async function runGenKeys({ root = REPO_ROOT, force = false, production = false, log = () => {} } = {}) {
  if (production) force = true;      // a label must never be moved onto keys that were already in use as dev keys
  const publicFile = publicKeysPath(root);
  const existingPublic = await readExistingPublicKeys(publicFile);

  // Phase 1: decide everything in memory, touch nothing on disk.
  const plan = [];
  for (const spec of KEY_SPECS) {
    const file = privateKeyPath(root, spec.name);
    if (existsSync(file) && !force) {
      const jwk = readPrivateKey(file, spec.name);
      await selfTest(jwk);
      plan.push({ spec, file, jwk, action: 'reuse' });
    } else {
      const exists = existsSync(file);
      let previousKid = null;
      if (exists) {
        try {
          previousKid = readPrivateKey(file, spec.name).kid;
        } catch {
          // unreadable old key: --force still replaces it, and it is kept as a backup either way
        }
      }
      const jwk = await generatePair(spec.name, nextKid(spec.name, previousKid));
      await selfTest(jwk);
      plan.push({ spec, file, jwk, action: 'generate', replaces: exists ? file : null });
    }
  }

  if (!force && existingPublic) {
    for (const { spec, jwk, action } of plan) {
      const shipped = existingPublic[spec.exportName];
      if (shipped && !sameKey(shipped, jwk)) {
        throw new ToolError(
          `${publicFile} already lists a different ${spec.exportName} than ${action === 'reuse' ? 'the private key in .keys/' : 'the one that would be generated (the private key is missing)'}. ` +
          'Replacing it would orphan everything signed for the current key. Restore the matching private key into .keys/, or pass --force to start over.',
        );
      }
    }
  }

  // Phase 2: write.
  const backups = [];
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  for (const item of plan) {
    if (item.action !== 'generate') continue;
    mkdirSync(dirname(item.file), { recursive: true });
    if (item.replaces) {
      const backup = join(dirname(item.file), `${item.spec.name}.private.jwk.${stamp}.bak.json`);
      renameSync(item.file, backup);
      backups.push(backup);
    }
    writeFileSync(item.file, `${JSON.stringify(item.jwk, null, 2)}\n`, { flag: 'wx', mode: 0o600 });
  }

  const publicKeys = Object.fromEntries(plan.map((item) => [item.spec.name, toPublicJwk(item.jwk)]));
  // An idempotent run (nothing regenerated) keeps the status the file already carries; anything else is 'dev' unless asked.
  const reused = plan.every((item) => item.action === 'reuse');
  const kept = reused && existingPublic && KEY_STATUSES.includes(existingPublic.KEY_STATUS) ? existingPublic.KEY_STATUS : 'dev';
  const status = production ? 'production' : (reused ? kept : 'dev');
  const text = renderPublicKeysModule(publicKeys, status);
  const unchanged = existsSync(publicFile) && readFileSync(publicFile, 'utf8') === text;
  if (!unchanged) writeAtomic(publicFile, text);

  for (const item of plan) {
    log(`${item.action === 'generate' ? 'generated' : 'kept     '} ${item.spec.name} key ${item.jwk.kid} (${item.spec.purpose}) -> ${item.file}`);
  }
  for (const backup of backups) log(`backed up previous private key -> ${backup}`);
  log(unchanged ? `${publicFile} already up to date` : `wrote ${publicFile}`);
  const gitignore = join(root, '.gitignore');
  if (existsSync(gitignore) && !/^\/?\.keys\/?\s*$/m.test(readFileSync(gitignore, 'utf8'))) {
    log('WARNING: .gitignore does not ignore .keys/ - add it before committing, the private keys live there.');
  }
  if (status === 'production') log('KEY_STATUS is production. Move the private keys out of .keys/ into a KMS/HSM or offline store and back them up; never commit them.');
  else log('These are DEV keys (KEY_STATUS = dev). Back up .keys/, never commit it, and replace the keys before any store release (npm run keys -- --production).');

  return {
    generated: plan.filter((p) => p.action === 'generate').map((p) => p.spec.name),
    reused: plan.filter((p) => p.action === 'reuse').map((p) => p.spec.name),
    backups,
    wrotePublicKeys: !unchanged,
    publicKeysFile: publicFile,
    status,
  };
}

const USAGE = 'usage: node tools/gen-keys.mjs [--force] [--production] [--root <dir>]';

export async function main(argv = process.argv.slice(2)) {
  let values;
  try {
    ({ values } = parseArgs({ args: argv, options: { force: { type: 'boolean' }, production: { type: 'boolean' }, root: { type: 'string' }, help: { type: 'boolean' } }, strict: true }));
  } catch (err) {
    console.error(`${err.message}\n${USAGE}`);
    return 2;
  }
  if (values.help) {
    console.log(USAGE);
    return 0;
  }
  try {
    await runGenKeys({ root: values.root ? resolve(values.root) : REPO_ROOT, force: Boolean(values.force), production: Boolean(values.production), log: (line) => console.log(line) });
    return 0;
  } catch (err) {
    console.error(`gen-keys: ${err.message}`);
    return 1;
  }
}

const isMain = process.argv[1] && resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase();
if (isMain) process.exitCode = await main();
